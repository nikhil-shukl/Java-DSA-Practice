// package Loops;

public class whileLoop {
    public static void main(String[] args) {
        int i=1;
        for(;i<=5;){
            System.out.println(i);
            i++;
        }
         
        System.out.println("while loop");  // all same work done by both while and for loop

        int j=1;
        while(j<=5){
            System.out.println(j);
            j++;
        }
    }
}
// use while loop if condition or increment complex