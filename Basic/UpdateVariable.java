public class UpdateVariable {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x);
         x = 7;                     // according new value variable change
        System.out.println(x);

        x = x + 11;                // assign 
        System.out.println(x);

        x = x - 20;              
        System.out.println(x);

    }
}
