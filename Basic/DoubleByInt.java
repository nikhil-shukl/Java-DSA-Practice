// package Basic;

public class DoubleByInt {
    public static void main(String[] args) {
        System.out.println(5/2);  // because both is integer 
        System.out.println(5.0/2.0);
        System.out.println(5/2.0);  // double hierarchy more then integer
        System.out.println(5.0/2);
    }
    
}
