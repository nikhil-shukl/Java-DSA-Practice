public class ArithmaticOperator {
    public static void main(String[] args) {
        int x = 5, y = 27;

        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(y / x);    // 5.4 instead 5 because of dataType int for print decimal use double data type
        System.out.println(x * y);

        // double and float data type use for print decimal value for float   A = 5f;
        double A, B ;

        A = 5;
        B = 27;
         System.out.println(B / A); 
         System.out.println(A + B);
    }
}
